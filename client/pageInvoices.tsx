import { useMemo, useState, type FormEvent } from "react";
import { useMutation } from "@tanstack/react-query";
import { api } from "./api";
import { downloadPdf, fmtMoney, prettyDate, todayStr, type Invoice } from "./lib";
import type { PageProps } from "./types";
import { Badge, EmptyState, Field, Modal } from "./components";

interface ItemDraft {
  description: string;
  qty: string;
  unitPrice: string;
}

function statusTone(status: string): "mint" | "warn" | "err" | "gold" | "grey" {
  if (status === "paid") return "mint";
  if (status === "overdue") return "err";
  if (status === "sent") return "gold";
  return "grey";
}

export function invoicePdfLines(state: PageProps["state"], inv: Invoice): string[] {
  const cur = state.business.currency;
  const lines = [
    state.business.name || "Cashflow Genius workspace",
    `${state.business.industry} · ${state.business.country}`,
    "",
    `Invoice ${inv.number}`,
    `Billed to: ${inv.customerName}${inv.customerEmail ? ` <${inv.customerEmail}>` : ""}`,
    `Issue date: ${prettyDate(inv.issueDate)}    Due date: ${prettyDate(inv.dueDate)}`,
    `Status: ${inv.effectiveStatus}`,
    "",
    "Items:",
    ...inv.items.map(
      (it) =>
        `  ${it.description}  x${it.qty} @ ${fmtMoney(it.unitPriceCents, cur, 2)} = ${fmtMoney(Math.round(it.qty * it.unitPriceCents), cur, 2)}`,
    ),
    "",
    `Subtotal: ${fmtMoney(inv.subtotalCents, cur, 2)}`,
    `Discount (${inv.discountPct}%): -${fmtMoney(inv.discountCents, cur, 2)}`,
    `Tax (${inv.taxPct}%): ${fmtMoney(inv.taxCents, cur, 2)}`,
    `TOTAL: ${fmtMoney(inv.totalCents, cur, 2)}`,
  ];
  if (inv.notes) lines.push("", `Notes: ${inv.notes}`);
  lines.push("", "Generated by Cashflow Genius — See money before it moves.");
  return lines;
}

export function InvoicesPage({ state, notify, notifyDeleted, confirm, saveToVault }: PageProps) {
  const cur = state.business.currency;
  const [showForm, setShowForm] = useState(false);
  const [editing, setEditing] = useState<Invoice | null>(null);
  const [openId, setOpenId] = useState<string | null>(null);
  const [filter, setFilter] = useState("all");

  const totals = useMemo(() => {
    const invoiced = state.invoices.reduce((a, i) => a + i.totalCents, 0);
    const outstanding = state.invoices
      .filter((i) => i.status === "sent")
      .reduce((a, i) => a + i.totalCents, 0);
    const overdue = state.invoices.filter((i) => i.effectiveStatus === "overdue");
    return { invoiced, outstanding, overdue };
  }, [state]);

  const markPaid = useMutation({
    mutationFn: (id: string) => api.markInvoicePaid({ id }),
    onSuccess: (res) => {
      if (res.ok) notify("Invoice marked paid — one linked income transaction was created.");
      else notify(res.error ?? "That invoice was already paid; no duplicate transaction was created.");
    },
    onError: (e) => notify(e instanceof Error ? e.message : String(e)),
  });
  const setStatus = useMutation({
    mutationFn: (args: { id: string; status: "draft" | "sent" }) => api.setInvoiceStatus(args),
    onSuccess: () => notify("Invoice status updated."),
    onError: (e) => notify(e instanceof Error ? e.message : String(e)),
  });
  const del = useMutation({
    mutationFn: (id: string) => api.deleteInvoice({ id }),
    onSuccess: (res, id) => {
      if (!res.ok) return notify(res.error ?? "Could not delete.");
      const inv = state.invoices.find((x) => x.id === id);
      notifyDeleted(`Draft invoice deleted — ${inv ? `${inv.number} (${inv.customerName})` : "invoice"}.`, res.trashId, inv?.number);
    },
    onError: (e) => notify(e instanceof Error ? e.message : String(e)),
  });

  const askMarkPaid = async (inv: Invoice) => {
    const ok = await confirm({
      title: `Mark invoice ${inv.number} as paid?`,
      body: "This records the money as received: exactly one linked income transaction is created in Money Flow, and the invoice can no longer be edited.",
      detail: `${inv.customerName} · ${fmtMoney(inv.totalCents, cur)} · due ${prettyDate(inv.dueDate)}`,
      confirmLabel: "Yes, mark paid",
    });
    if (ok) markPaid.mutate(inv.id);
  };

  const askDeleteInvoice = async (inv: Invoice) => {
    const ok = await confirm({
      title: `Delete draft invoice ${inv.number}?`,
      body: "The draft and all its line items will be removed. You can undo it right after from the Undo button.",
      detail: `${inv.customerName} · ${fmtMoney(inv.totalCents, cur)} · ${inv.items.length} item(s)`,
      confirmLabel: "Delete invoice",
      danger: true,
    });
    if (ok) del.mutate(inv.id);
  };

  const shown = state.invoices.filter(
    (i) => filter === "all" || i.effectiveStatus === filter,
  );
  const open = state.invoices.find((i) => i.id === openId) ?? null;

  const nextNumber = () => {
    const year = new Date().getFullYear();
    return `INV-${year}-${String(state.invoices.length + 1).padStart(3, "0")}`;
  };

  return (
    <div className="page-anim space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="display-font text-[27px] font-semibold tracking-tight">Invoices</h1>
          <p className="text-sm text-[var(--dim)]">
            Marking an invoice paid creates exactly one linked income transaction —
            duplicates are blocked in the database.
          </p>
        </div>
        <button
          type="button"
          className="btn-primary px-5 py-2.5 text-sm"
          onClick={() => {
            setEditing(null);
            setShowForm(true);
          }}
        >
          + Create invoice
        </button>
      </div>

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
        <article className="card p-4">
          <p className="text-xs font-bold uppercase tracking-wide text-[var(--dim)]">Total invoiced</p>
          <p className="mt-1 text-2xl font-extrabold">{fmtMoney(totals.invoiced, cur)}</p>
        </article>
        <article className="card p-4">
          <p className="text-xs font-bold uppercase tracking-wide text-[var(--dim)]">Outstanding</p>
          <p className="mt-1 text-2xl font-extrabold">{fmtMoney(totals.outstanding, cur)}</p>
        </article>
        <article className="card p-4">
          <p className="text-xs font-bold uppercase tracking-wide text-[var(--dim)]">Overdue invoices</p>
          <p className="mt-1 text-2xl font-extrabold">
            {totals.overdue.length}
            <span className="ml-2 text-base font-bold text-[#e11d63]">
              {fmtMoney(totals.overdue.reduce((a, i) => a + i.totalCents, 0), cur)}
            </span>
          </p>
        </article>
      </div>

      <div className="flex flex-wrap gap-2" role="group" aria-label="Filter invoices by status">
        {["all", "draft", "sent", "paid", "overdue"].map((f) => (
          <button
            key={f}
            type="button"
            aria-pressed={filter === f}
            onClick={() => setFilter(f)}
            className={`px-4 py-1.5 text-sm capitalize ${filter === f ? "btn-primary" : "btn-ghost"}`}
          >
            {f}
          </button>
        ))}
      </div>

      {shown.length === 0 ? (
        <EmptyState
          title={state.invoices.length === 0 ? "No invoices yet" : "No invoices with this status"}
          body="Create an invoice with line items, discount and tax — totals calculate automatically. When it is paid, the money lands in your ledger exactly once."
          action={
            state.invoices.length === 0 ? (
              <button
                type="button"
                className="btn-primary px-5 py-2.5 text-sm"
                onClick={() => {
                  setEditing(null);
                  setShowForm(true);
                }}
              >
                Create your first invoice
              </button>
            ) : undefined
          }
        />
      ) : (
        <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
          {shown.map((inv, i) => (
            <article key={inv.id} className="card rise p-5" style={{ animationDelay: `${Math.min(i, 6) * 60}ms` }}>
              <div className="flex items-start justify-between gap-3">
                <div>
                  <p className="font-extrabold">{inv.number}</p>
                  <p className="text-sm text-[var(--dim)]">{inv.customerName}</p>
                </div>
                <Badge tone={statusTone(inv.effectiveStatus)}>
                  {inv.effectiveStatus}
                </Badge>
              </div>
              <p className="mt-3 text-2xl font-extrabold">{fmtMoney(inv.totalCents, cur)}</p>
              <p className="mt-1 text-xs text-[var(--dim)]">
                Issued {prettyDate(inv.issueDate)} · Due {prettyDate(inv.dueDate)}
                {inv.demo ? " · Demo" : ""}
              </p>
              <div className="mt-4 flex flex-wrap gap-2">
                <button type="button" className="btn-ghost px-3 py-1.5 text-xs" onClick={() => setOpenId(inv.id)}>
                  Open
                </button>
                <button
                  type="button"
                  className="btn-ghost px-3 py-1.5 text-xs"
                  onClick={() => downloadPdf(`invoice-${inv.number}.pdf`, `Invoice ${inv.number}`, invoicePdfLines(state, inv))}
                >
                  Download PDF
                </button>
                {inv.status !== "paid" ? (
                  <>
                    <button
                      type="button"
                      className="btn-ghost px-3 py-1.5 text-xs"
                      onClick={() => {
                        setEditing(inv);
                        setShowForm(true);
                      }}
                    >
                      Edit
                    </button>
                    <button
                      type="button"
                      className="btn-ghost px-3 py-1.5 text-xs"
                      onClick={() =>
                        setStatus.mutate({ id: inv.id, status: inv.status === "draft" ? "sent" : "draft" })
                      }
                    >
                      {inv.status === "draft" ? "Mark sent" : "Back to draft"}
                    </button>
                    <button
                      type="button"
                      className="btn-primary px-3 py-1.5 text-xs"
                      disabled={markPaid.isPending}
                      onClick={() => void askMarkPaid(inv)}
                    >
                      Mark paid
                    </button>
                    {inv.status === "draft" ? (
                      <button
                        type="button"
                        className="btn-ghost px-3 py-1.5 text-xs"
                        onClick={() => void askDeleteInvoice(inv)}
                      >
                        Delete draft
                      </button>
                    ) : null}
                  </>
                ) : null}
                <button
                  type="button"
                  className="btn-ghost px-3 py-1.5 text-xs"
                  onClick={() =>
                    saveToVault(
                      `Invoice follow-up: ${inv.number}`,
                      `Invoice ${inv.number} for ${inv.customerName}: ${fmtMoney(inv.totalCents, cur)}, status ${inv.effectiveStatus}, due ${prettyDate(inv.dueDate)}.`,
                      "Invoice Intelligence",
                    )
                  }
                >
                  Save follow-up note
                </button>
              </div>
            </article>
          ))}
        </div>
      )}

      {open ? (
        <Modal title={`Invoice ${open.number}`} onClose={() => setOpenId(null)} wide>
          <div className="space-y-4">
            <div className="flex flex-wrap items-center justify-between gap-2">
              <div>
                <p className="font-bold">{open.customerName}</p>
                <p className="text-sm text-[var(--dim)]">{open.customerEmail || "No email on file"}</p>
              </div>
              <Badge tone={statusTone(open.effectiveStatus)}>{open.effectiveStatus}</Badge>
            </div>
            <div className="overflow-x-auto">
              <table className="w-full min-w-[420px] text-sm">
                <thead>
                  <tr className="border-b border-[var(--border)] text-left text-xs uppercase tracking-wide text-[var(--dim)]">
                    <th className="py-2 pr-3">Item</th>
                    <th className="py-2 pr-3 text-right">Qty</th>
                    <th className="py-2 pr-3 text-right">Unit price</th>
                    <th className="py-2 text-right">Amount</th>
                  </tr>
                </thead>
                <tbody>
                  {open.items.map((it) => (
                    <tr key={it.id} className="border-b border-[var(--border)] last:border-0">
                      <td className="py-2 pr-3">{it.description}</td>
                      <td className="py-2 pr-3 text-right">{it.qty}</td>
                      <td className="py-2 pr-3 text-right">{fmtMoney(it.unitPriceCents, cur, 2)}</td>
                      <td className="py-2 text-right font-semibold">
                        {fmtMoney(Math.round(it.qty * it.unitPriceCents), cur, 2)}
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
            <dl className="space-y-1 text-sm">
              <div className="flex justify-between"><dt className="text-[var(--dim)]">Subtotal</dt><dd className="font-semibold">{fmtMoney(open.subtotalCents, cur, 2)}</dd></div>
              <div className="flex justify-between"><dt className="text-[var(--dim)]">Discount ({open.discountPct}%)</dt><dd className="font-semibold">−{fmtMoney(open.discountCents, cur, 2).replace("−", "")}</dd></div>
              <div className="flex justify-between"><dt className="text-[var(--dim)]">Tax ({open.taxPct}%)</dt><dd className="font-semibold">{fmtMoney(open.taxCents, cur, 2)}</dd></div>
              <div className="flex justify-between border-t border-[var(--border)] pt-2 text-base"><dt className="font-extrabold">Total</dt><dd className="font-extrabold">{fmtMoney(open.totalCents, cur, 2)}</dd></div>
            </dl>
            <p className="text-sm text-[var(--dim)]">
              Issued {prettyDate(open.issueDate)} · Due {prettyDate(open.dueDate)}
              {open.notes ? ` · ${open.notes}` : ""}
            </p>
            <div className="flex flex-wrap justify-end gap-2">
              <button
                type="button"
                className="btn-ghost px-4 py-2 text-sm"
                onClick={() => downloadPdf(`invoice-${open.number}.pdf`, `Invoice ${open.number}`, invoicePdfLines(state, open))}
              >
                Download PDF
              </button>
              {open.status !== "paid" ? (
                <button
                  type="button"
                  className="btn-primary px-5 py-2 text-sm"
                  disabled={markPaid.isPending}
                  onClick={() => void askMarkPaid(open)}
                >
                  Mark paid
                </button>
              ) : null}
            </div>
          </div>
        </Modal>
      ) : null}

      {showForm ? (
        <InvoiceForm
          initial={editing}
          currency={cur}
          suggestedNumber={nextNumber()}
          defaultTaxPct={state.business.gstRateBp / 100}
          onClose={() => setShowForm(false)}
          notify={notify}
        />
      ) : null}
    </div>
  );
}

function InvoiceForm({
  initial,
  currency,
  suggestedNumber,
  defaultTaxPct,
  onClose,
  notify,
}: {
  initial: Invoice | null;
  currency: string;
  suggestedNumber: string;
  defaultTaxPct: number;
  onClose: () => void;
  notify: (m: string) => void;
}) {
  const [number, setNumber] = useState(initial?.number ?? suggestedNumber);
  const [customerName, setCustomerName] = useState(initial?.customerName ?? "");
  const [customerEmail, setCustomerEmail] = useState(initial?.customerEmail ?? "");
  const [status, setStatus] = useState<"draft" | "sent">(initial?.status === "sent" ? "sent" : "draft");
  const [issueDate, setIssueDate] = useState(initial?.issueDate ?? todayStr());
  const [dueDate, setDueDate] = useState(initial?.dueDate ?? todayStr());
  const [discountPct, setDiscountPct] = useState(String(initial?.discountPct ?? 0));
  const [taxPct, setTaxPct] = useState(String(initial?.taxPct ?? defaultTaxPct));
  const [notes, setNotes] = useState(initial?.notes ?? "");
  const [items, setItems] = useState<ItemDraft[]>(
    initial
      ? initial.items.map((it) => ({
          description: it.description,
          qty: String(it.qty),
          unitPrice: String(it.unitPriceCents / 100),
        }))
      : [{ description: "", qty: "1", unitPrice: "" }],
  );
  const [error, setError] = useState<string | null>(null);

  const subtotal = items.reduce((a, it) => {
    const q = parseFloat(it.qty) || 0;
    const p = parseFloat(it.unitPrice) || 0;
    return a + Math.round(q * p * 100);
  }, 0);
  const discount = Math.round(subtotal * ((parseFloat(discountPct) || 0) / 100));
  const tax = Math.round((subtotal - discount) * ((parseFloat(taxPct) || 0) / 100));
  const total = subtotal - discount + tax;

  const save = useMutation({
    mutationFn: () =>
      api.saveInvoice({
        id: initial?.id,
        number: number.trim(),
        customerName: customerName.trim(),
        customerEmail: customerEmail.trim(),
        status,
        issueDate,
        dueDate,
        discountPct: parseFloat(discountPct) || 0,
        taxPct: parseFloat(taxPct) || 0,
        notes,
        items: items.map((it) => ({
          description: it.description,
          qty: parseFloat(it.qty) || 0,
          unitPriceCents: Math.round((parseFloat(it.unitPrice) || 0) * 100),
        })),
      }),
    onSuccess: () => {
      notify(initial ? "Invoice updated." : "Invoice created.");
      onClose();
    },
    onError: (e) => setError(e instanceof Error ? e.message : String(e)),
  });

  const onSubmit = (e: FormEvent) => {
    e.preventDefault();
    if (!number.trim()) return setError("Give the invoice a number.");
    if (!customerName.trim()) return setError("Add the customer name.");
    if (items.some((it) => (parseFloat(it.qty) || 0) <= 0)) {
      return setError("Every item needs a quantity above zero.");
    }
    if (dueDate < issueDate) return setError("The due date cannot be before the issue date.");
    save.mutate();
  };

  return (
    <Modal title={initial ? `Edit invoice ${initial.number}` : "Create invoice"} onClose={onClose} wide>
      <form className="space-y-4" onSubmit={onSubmit}>
        <div className="grid grid-cols-2 gap-3">
          <Field label="Invoice number">
            <input className="field" value={number} onChange={(e) => setNumber(e.target.value)} aria-label="Invoice number" required />
          </Field>
          <Field label="Status">
            <select className="field" value={status} aria-label="Invoice status" onChange={(e) => setStatus(e.target.value === "sent" ? "sent" : "draft")}>
              <option value="draft">Draft</option>
              <option value="sent">Sent</option>
            </select>
          </Field>
        </div>
        <div className="grid grid-cols-2 gap-3">
          <Field label="Customer name">
            <input className="field" value={customerName} onChange={(e) => setCustomerName(e.target.value)} aria-label="Customer name" required />
          </Field>
          <Field label="Customer email">
            <input className="field" type="email" value={customerEmail} onChange={(e) => setCustomerEmail(e.target.value)} aria-label="Customer email" />
          </Field>
        </div>
        <div className="space-y-3">
          <p className="text-xs font-bold uppercase tracking-wide text-[var(--dim)]">Line items</p>
          {items.map((it, i) => (
            <div key={i} className="grid grid-cols-[1fr_70px_110px_36px] items-end gap-2">
              <Field label={i === 0 ? "Description" : ""}>
                <input
                  className="field"
                  value={it.description}
                  aria-label={`Item ${i + 1} description`}
                  onChange={(e) => setItems((arr) => arr.map((x, j) => (j === i ? { ...x, description: e.target.value } : x)))}
                  placeholder="Service or product"
                />
              </Field>
              <Field label={i === 0 ? "Qty" : ""}>
                <input
                  className="field"
                  type="number"
                  min="0"
                  step="0.001"
                  value={it.qty}
                  aria-label={`Item ${i + 1} quantity`}
                  onChange={(e) => setItems((arr) => arr.map((x, j) => (j === i ? { ...x, qty: e.target.value } : x)))}
                />
              </Field>
              <Field label={i === 0 ? "Unit price" : ""}>
                <input
                  className="field"
                  type="number"
                  min="0"
                  step="1"
                  value={it.unitPrice}
                  aria-label={`Item ${i + 1} unit price`}
                  onChange={(e) => setItems((arr) => arr.map((x, j) => (j === i ? { ...x, unitPrice: e.target.value } : x)))}
                />
              </Field>
              <button
                type="button"
                className="btn-ghost flex h-10 w-9 items-center justify-center"
                aria-label={`Remove item ${i + 1}`}
                disabled={items.length === 1}
                onClick={() => setItems((arr) => arr.filter((_, j) => j !== i))}
              >
                ×
              </button>
            </div>
          ))}
          <button
            type="button"
            className="btn-ghost px-4 py-1.5 text-xs"
            onClick={() => setItems((arr) => [...arr, { description: "", qty: "1", unitPrice: "" }])}
          >
            + Add item
          </button>
        </div>
        <div className="grid grid-cols-2 gap-3">
          <Field label="Issue date">
            <input className="field" type="date" value={issueDate} onChange={(e) => setIssueDate(e.target.value)} aria-label="Issue date" required />
          </Field>
          <Field label="Due date">
            <input className="field" type="date" value={dueDate} onChange={(e) => setDueDate(e.target.value)} aria-label="Due date" required />
          </Field>
          <Field label="Discount %">
            <input className="field" type="number" min="0" max="100" step="0.01" value={discountPct} onChange={(e) => setDiscountPct(e.target.value)} aria-label="Discount percent" />
          </Field>
          <Field label="Tax % (e.g. GST)">
            <input className="field" type="number" min="0" max="100" step="0.01" value={taxPct} onChange={(e) => setTaxPct(e.target.value)} aria-label="Tax percent" />
          </Field>
        </div>
        <Field label="Notes">
          <input className="field" value={notes} onChange={(e) => setNotes(e.target.value)} aria-label="Invoice notes" maxLength={500} />
        </Field>
        <div className="rounded-xl bg-[var(--surface-soft)] px-4 py-3 text-sm">
          <div className="flex justify-between"><span>Subtotal</span><strong>{fmtMoney(subtotal, currency, 2)}</strong></div>
          <div className="flex justify-between"><span>Discount</span><strong>−{fmtMoney(discount, currency, 2).replace("−", "")}</strong></div>
          <div className="flex justify-between"><span>Tax</span><strong>{fmtMoney(tax, currency, 2)}</strong></div>
          <div className="mt-1 flex justify-between border-t border-[var(--border)] pt-1 text-base"><span className="font-extrabold">Total</span><strong>{fmtMoney(total, currency, 2)}</strong></div>
        </div>
        {error ? <p className="rounded-xl bg-[var(--err)] px-3 py-2 text-sm text-[var(--err-text)]" role="alert">{error}</p> : null}
        <div className="flex justify-end gap-2">
          <button type="button" className="btn-ghost px-5 py-2.5 text-sm" onClick={onClose}>Cancel</button>
          <button type="submit" className="btn-primary px-6 py-2.5 text-sm" disabled={save.isPending}>
            {save.isPending ? "Saving…" : "Save invoice"}
          </button>
        </div>
      </form>
    </Modal>
  );
}
